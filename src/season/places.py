@dataclass(frozen=True)
class Spot:
    """지도의 점 하나. label 은 라벨이 점의 어느 쪽에 붙는지(basemap.OFFSETS)."""
    name: str
    lat: float
    lon: float
    label: str = "r"


def spot(name: str, label: str = "r") -> Spot:
    """좌표가 없는 이름은 KeyError — 조용히 지도에서 빠지지 않게."""
    lat, lon = LAT_LON[name]
    return Spot(name, lat, lon, label)
